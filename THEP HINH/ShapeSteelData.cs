    public enum ShapeType
    {
        EqualAngle,
        UnequalAngle,
        IBeam,
        Channel,
        HBeam,
        SheetPile
    }

    /// <summary>Tieu chuan tra cuu</summary>
    public enum Standard
    {
        TCVN,       // TCVN 7571 - Vietnam
        JIS,        // JIS G 3192 - Nhat
        ASTM        // ASTM A6 / W-Shape - My
    }

    public class SteelProfile
    {
        public string Designation { get; set; }
        public double H { get; set; }              // mm
        public double B { get; set; }              // mm
        public double t { get; set; }              // mm (t1 - web)
        public double tf { get; set; }             // mm (t2 - flange)
        public double r1 { get; set; }             // mm
        public double r2 { get; set; }             // mm
        public double Weight { get; set; }         // kg/m
        public double Area { get; set; }           // cm2
        public double Cx { get; set; }             // cm
        public double Cy { get; set; }             // cm
        public double Ix { get; set; }             // cm4
        public double Iy { get; set; }             // cm4
        public double Imax { get; set; }
        public double Imin { get; set; }
        public double ix { get; set; }             // cm
        public double iy { get; set; }             // cm
        public double imax { get; set; }
        public double imin { get; set; }
        public double Zx { get; set; }             // cm3
        public double Zy { get; set; }             // cm3
        public bool IsCommon { get; set; }
    }

    public static class ShapeSteelData
    {
        /// <summary>Lay du lieu theo loai va tieu chuan.</summary>
        public static List<SteelProfile> Get(ShapeType type, Standard std = Standard.TCVN)
        {
            switch (std)
            {
                case Standard.JIS:  return GetJIS(type);
                case Standard.ASTM: return GetASTM(type);
                case Standard.TCVN:
                default:            return GetTCVN(type);
            }
        }

        private static List<SteelProfile> GetTCVN(ShapeType type)
        {
            switch (type)
            {
                case ShapeType.EqualAngle:   return EqualAngles();
                case ShapeType.UnequalAngle: return UnequalAngles();
                case ShapeType.IBeam:        return IBeams();
                case ShapeType.Channel:      return Channels();
                case ShapeType.HBeam:        return HBeams();
                case ShapeType.SheetPile:    return SheetPiles();
                default: return new List<SteelProfile>();
            }
        }

